create or replace function jupa_v3.v3_save_visit_legacy(p_values jsonb,p_assignments jsonb) returns public.actividades language plpgsql security definer set search_path='' as $$
declare v public.actividades; vid bigint; r text; pid bigint; assigned public.responsabilidades;
begin
 -- Solo invocada desde save_visit tras comprobar permisos.
 vid:=coalesce((p_values->>'id')::bigint,nextval('public.actividades_id_seq'));
 select * into v from public.actividades where id=vid for update;
 if v.id is not null then
  if v.version<>coalesce((p_values->>'version')::integer,0) then raise exception 'La visita fue modificada por otro usuario. Actualiza antes de guardar.' using errcode='40001'; end if;
  update public.actividades set date=(p_values->>'date')::date,iglesia_id=(p_values->>'class_id')::bigint,"group"=p_values->>'group',notas=coalesce(p_values->>'notes',''),version=version+1 where id=vid returning * into v;
 else
  insert into public.actividades(id,date,iglesia_id,"group",notas) values(vid,(p_values->>'date')::date,(p_values->>'class_id')::bigint,p_values->>'group',coalesce(p_values->>'notes','')) returning * into v;
 end if;
 foreach r in array array['Predicación','Coordinación','Dirección del coro'] loop
  if p_assignments ? r then
   pid:=nullif(p_assignments->>r,'')::bigint;
   select * into assigned from public.responsabilidades where actividad_id=vid and rol=r;
   if pid is null then
    if assigned.id is not null and (assigned.resultado<>'Pendiente' or assigned.realizado_por is not null or assigned.observacion<>'') then raise exception 'No se puede quitar una función con resultado registrado. Conserva su historial.'; end if;
    delete from public.responsabilidades where actividad_id=vid and rol=r;
   elsif assigned.id is null then
    if not exists(select 1 from public.miembros where id=pid and activo and fusionado_en is null) then raise exception 'El responsable no está activo.'; end if;
    insert into public.responsabilidades(actividad_id,rol,miembro_id,actualizado_por) values(vid,r,pid,auth.uid());
   elsif assigned.miembro_id<>pid then
    if assigned.resultado<>'Pendiente' or assigned.realizado_por is not null or assigned.observacion<>'' then raise exception 'La función ya tiene resultado. Registra el reemplazo en quién realizó la función.'; end if;
    if not exists(select 1 from public.miembros where id=pid and activo and fusionado_en is null) then raise exception 'El responsable no está activo.'; end if;
    update public.responsabilidades set miembro_id=pid,version=version+1,actualizado_por=auth.uid(),actualizado_el=now() where id=assigned.id;
   end if;
  end if;
 end loop;
 return v;
end;
$$;

create function public.v3_save_visit(p_values jsonb,p_assignments jsonb) returns public.actividades language plpgsql security definer set search_path='' as $$
declare v public.actividades; old_v public.actividades; vid bigint; m text; c bigint; new_date date;
begin
 m:=coalesce(p_values->>'activity_type','visita'); c:=(p_values->>'class_id')::bigint; new_date:=(p_values->>'date')::date;
 if not jupa_v3.can_activity(m,c,'manage') then raise exception 'No tienes permiso para programar esta actividad.' using errcode='42501'; end if;
 vid:=nullif(p_values->>'id','')::bigint;
 if vid is not null then
  select * into old_v from public.actividades where id=vid for update;
  if old_v.id is null or not jupa_v3.can_visit(vid,'manage') then raise exception 'Actividad no disponible.'; end if;
  if old_v.date <= (now() at time zone 'America/Santiago')::date then perform jupa_v3.check_edit(vid); end if;
  if old_v.version<>coalesce((p_values->>'version')::integer,0) then raise exception 'La actividad fue modificada. Actualiza antes de guardar.' using errcode='40001'; end if;
  if m<>old_v.tipo_actividad or c<>old_v.iglesia_id or new_date<>old_v.date or p_values->>'group'<>old_v."group" then raise exception 'Fecha, clase, tipo y grupo no se cambian después de crear la actividad. Conserva el historial.'; end if;
 end if;
 if new_date < (now() at time zone 'America/Santiago')::date-21 and not jupa_v3.is_admin() then raise exception 'Solo el administrador puede crear actividades de hace más de 21 días.'; end if;
 if m='visita' and not exists(select 1 from public.usuarios where id=auth.uid() and rol in ('admin','jefatura')) then raise exception 'Solo la administración central programa visitas.'; end if;
 if m='visita' then
  v:=jupa_v3.v3_save_visit_legacy(p_values,p_assignments);
 else
  if vid is null then
   insert into public.actividades(date,iglesia_id,"group",notas,tipo_actividad,iglesia_sede_id) values(new_date,c,case when m='visita' then p_values->>'group' else 'Todos' end,coalesce(p_values->>'notes',''),m,coalesce(nullif(p_values->>'venue_class_id','')::bigint,c)) returning * into v;
  else
   update public.actividades set notas=coalesce(p_values->>'notes',''),iglesia_sede_id=coalesce(nullif(p_values->>'venue_class_id','')::bigint,c),version=version+1 where id=vid returning * into v;
  end if;
 end if;
 return v;
end; $$;
