 if p_status not in ('pending','held','suspended') then raise exception 'Estado inválido.'; end if;
 if p_status in ('suspended','pending') and exists(select 1 from public.asistencias where actividad_id=p_id and presente) then raise exception 'Hay asistentes registrados. Revisa las marcas antes de suspender o dejar pendiente.'; end if;
 if p_status='suspended' and length(trim(coalesce(p_reason,'')))=0 then raise exception 'Indica por qué no hubo actividad.'; end if;
 update public.actividades set estado=p_status,motivo_suspension=case when p_status='suspended' then p_reason else '' end,iglesia_sede_id=coalesce(p_venue,iglesia_id),version=version+1 where id=p_id returning * into v;
 return v;
end; $$;
create function public.v3_ensure_sundays(p_from date,p_to date) returns integer language plpgsql security definer set search_path='' as $$
declare c public.iglesias; m text; d date; n integer:=0; inserted integer;
begin
 if not jupa_v3.is_member() then raise exception 'Sin acceso.' using errcode='42501'; end if;
 if p_from is null or p_to is null or p_to<p_from or p_to-p_from>93 then raise exception 'Selecciona un período de hasta tres meses.'; end if;
 for c in select * from public.iglesias where activo loop
  foreach m in array array['escuela_dominical','servicio_domingo'] loop
   if not jupa_v3.can_activity(m,c.id,'manage') then continue; end if;
   for d in select x::date from generate_series(p_from::timestamp,p_to::timestamp,interval '1 day') x where extract(dow from x)=0 loop
    if not jupa_v3.is_admin() and d<(now() at time zone 'America/Santiago')::date-21 then continue; end if;
    insert into public.actividades(date,iglesia_id,"group",tipo_actividad,iglesia_sede_id) values(d,c.id,'Todos',m,c.id) on conflict(date,iglesia_id,"group",tipo_actividad) do nothing;
    get diagnostics inserted=row_count; n:=n+inserted;
   end loop;
  end loop;
 end loop;
 return n;
end; $$;

