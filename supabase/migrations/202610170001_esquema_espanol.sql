begin
 perform jupa_v3.require_admin();
 if p_source=p_target then raise exception 'Selecciona dos registros diferentes.'; end if;
 perform 1 from public.miembros where id in(p_source,p_target) order by id for update;
 select * into s from public.miembros where id=p_source;
 select * into t from public.miembros where id=p_target;
