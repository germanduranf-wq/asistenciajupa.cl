CREATE FUNCTION public.v3_public_bulletin(p_month date) RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
DECLARE first_day date; next_month date; result jsonb;
BEGIN
 IF p_month IS NULL OR p_month < date '2000-01-01' OR p_month > date '2100-12-31' THEN RAISE EXCEPTION 'Mes no válido.'; END IF;
 first_day:=date_trunc('month',p_month)::date; next_month:=(first_day+interval '1 month')::date;
 SELECT jsonb_build_object('month',first_day,
 'highlight',coalesce((SELECT mensaje FROM public.avisos_destacados WHERE mes=first_day AND publicado),''),
 'activities',coalesce((SELECT jsonb_agg(jsonb_build_object('id',v.id,'date',v.date,'type',v.tipo_actividad,'group',v."group",'time',v.hora,'class_name',c.nombre,'address',c.direccion,'commune',c.comuna,'maps_url',c.enlace_mapa,'status',v.estado) ORDER BY v.date,v."group") FROM public.actividades v JOIN public.iglesias c ON c.id=coalesce(v.iglesia_sede_id,v.iglesia_id) JOIN public.modulos m ON m.codigo=v.tipo_actividad AND m.habilitado WHERE v.date>=first_day AND v.date<next_month AND v.tipo_actividad IN ('visita','reunion_encargados','devocional')),'[]'::jsonb),
 'events',coalesce((SELECT jsonb_agg(jsonb_build_object('id',e.id,'kind',e.tipo,'date',e.date,'title',e.titulo,'description',e.descripcion,'venue',e.lugar,'address',e.direccion,'maps_url',e.enlace_mapa,'morning_time',e.hora_manana,'evening_time',e.hora_tarde,'preaching_place',e.punto_predicacion,'preaching_maps_url',e.mapa_predicacion,'hosts',(SELECT jsonb_agg(c.nombre ORDER BY c.nombre) FROM public.iglesias c WHERE c.id=ANY(e.anfitrionas_ids))) ORDER BY e.date,e.titulo) FROM public.eventos e WHERE e.publicado AND e.date>=first_day AND e.date<next_month),'[]'::jsonb)) INTO result;
 RETURN result;
END; $$;
