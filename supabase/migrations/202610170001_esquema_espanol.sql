create function public.v3_set_attendance(p_visit bigint,p_person bigint,p_present boolean,p_version integer)
returns public.asistencias language plpgsql security definer set search_path='' as $$
declare old_record public.asistencias; person public.miembros; answer public.asistencias;
begin
 perform jupa_v3.check_edit(p_visit);
 -- Bloqueo compartido con la fusión: no se crean nuevas marcas en una persona ya fusionada.
 select * into person from public.miembros where id=p_person for share;
 if person.id is null or person.fusionado_en is not null then raise exception 'El participante no está disponible.'; end if;
 perform pg_advisory_xact_lock(hashtext(p_visit::text),hashtext(p_person::text));
 select * into old_record from public.asistencias where actividad_id=p_visit and miembro_id=p_person for update;
 if coalesce(old_record.version,0)<>p_version then raise exception 'Otro encargado modificó esta asistencia. Actualiza e inténtalo de nuevo.' using errcode='40001'; end if;
 if p_present is null then raise exception 'Indica el estado de asistencia.'; end if;
 insert into public.asistencias(actividad_id,miembro_id,presente,iglesia_id,categoria,version,actualizado_por)
 values(p_visit,p_person,p_present,coalesce(old_record.iglesia_id,person.iglesia_id),coalesce(old_record.categoria,person.categoria),p_version+1,auth.uid())
 on conflict(actividad_id,miembro_id) do update set presente=excluded.presente,version=excluded.version,actualizado_por=excluded.actualizado_por,actualizado_el=now()
 returning * into answer;
 return answer;
end;
$$;
create function public.v3_save_visit(p_values jsonb,p_assignments jsonb) returns public.actividades language plpgsql security definer set search_path='' as $$
declare v public.actividades; vid bigint; r text; pid bigint; assigned public.responsabilidades;
begin
 perform jupa_v3.require_admin();
 vid:=coalesce((p_values->>'id')::bigint,nextval('public.actividades_id_seq'));
 select * into v from public.actividades where id=vid for update;
 if v.id is not null then
  if v.version<>coalesce((p_values->>'version')::integer,0) then raise exception 'La visita fue modificada por otro usuario. Actualiza antes de guardar.' using errcode='40001'; end if;
  update public.actividades set date=(p_values->>'date')::date,iglesia_id=(p_values->>'class_id')::bigint,"group"=p_values->>'group',notas=coalesce(p_values->>'notes',''),version=version+1 where id=vid returning * into v;
 else
  insert into public.actividades(id,date,iglesia_id,"group",notas) values(vid,(p_values->>'date')::date,(p_values->>'class_id')::bigint,p_values->>'group',coalesce(p_values->>'notes','')) returning * into v;
 end if;
 foreach r in array array['Predicación','Coordinación','Dirección del coro'] loop
  if p_assignments ? r then
   pid:=nullif(p_assignments->>r,'')::bigint;
   select * into assigned from public.responsabilidades where actividad_id=vid and rol=r;
   if pid is null then
    if assigned.id is not null and (assigned.resultado<>'Pendiente' or assigned.realizado_por is not null or assigned.observacion<>'') then raise exception 'No se puede quitar una función con resultado registrado. Conserva su historial.'; end if;
    delete from public.responsabilidades where actividad_id=vid and rol=r;
   elsif assigned.id is null then
    if not exists(select 1 from public.miembros where id=pid and activo and fusionado_en is null) then raise exception 'El responsable no está activo.'; end if;
    insert into public.responsabilidades(actividad_id,rol,miembro_id,actualizado_por) values(vid,r,pid,auth.uid());
   elsif assigned.miembro_id<>pid then
    if assigned.resultado<>'Pendiente' or assigned.realizado_por is not null or assigned.observacion<>'' then raise exception 'La función ya tiene resultado. Registra el reemplazo en quién realizó la función.'; end if;
    if not exists(select 1 from public.miembros where id=pid and activo and fusionado_en is null) then raise exception 'El responsable no está activo.'; end if;
    update public.responsabilidades set miembro_id=pid,version=version+1,actualizado_por=auth.uid(),actualizado_el=now() where id=assigned.id;
   end if;
  end if;
 end loop;
 return v;
end;
$$;
create function public.v3_set_responsibility(p_id bigint,p_outcome text,p_actual bigint,p_note text,p_version integer) returns void language plpgsql security definer set search_path='' as $$
declare r public.responsabilidades;
begin
 select * into r from public.responsabilidades where id=p_id for update;
 if r.id is null then raise exception 'La función no existe.'; end if;
 perform jupa_v3.check_edit(r.actividad_id);
 if r.version<>p_version then raise exception 'Otro encargado modificó este resultado. Actualiza e inténtalo de nuevo.' using errcode='40001'; end if;
